#!/usr/bin/env python3
"""Generate offline lookup tables and an antialiased 2-bit CJK glyph atlas."""
import json
import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "assets/ime"
OUT = ROOT / "build/ime_data.h"

ZHUYIN_KEYS = dict(zip("ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙㄧㄨㄩㄚㄛㄜㄝㄞㄟㄠㄡㄢㄣㄤㄥㄦ",
                       "1qaz2wsxedcrfv5tgbyhnujm8ik,9ol.0p;/-"))
INITIALS = dict(zip(
    "b p m f d t n l g k h j q x zh ch sh r z c s".split(),
    "ㄅㄆㄇㄈㄉㄊㄋㄌㄍㄎㄏㄐㄑㄒㄓㄔㄕㄖㄗㄘㄙ"))
FINALS = dict(item.split("=") for item in (
    "a=ㄚ o=ㄛ e=ㄜ ai=ㄞ ei=ㄟ ao=ㄠ ou=ㄡ an=ㄢ en=ㄣ ang=ㄤ eng=ㄥ er=ㄦ "
    "i=ㄧ ia=ㄧㄚ io=ㄧㄛ ie=ㄧㄝ iai=ㄧㄞ iao=ㄧㄠ iu=ㄧㄡ iou=ㄧㄡ ian=ㄧㄢ in=ㄧㄣ iang=ㄧㄤ ing=ㄧㄥ "
    "u=ㄨ ua=ㄨㄚ uo=ㄨㄛ uai=ㄨㄞ ui=ㄨㄟ uei=ㄨㄟ uan=ㄨㄢ un=ㄨㄣ uen=ㄨㄣ uang=ㄨㄤ ueng=ㄨㄥ ong=ㄨㄥ "
    "v=ㄩ ve=ㄩㄝ van=ㄩㄢ vn=ㄩㄣ iong=ㄩㄥ ue=ㄩㄝ").split())
SEMIVOWELS = dict(item.split("=") for item in (
    "yi=i ya=ia yo=io ye=ie yao=iao you=iu yan=ian yin=in yang=iang ying=ing "
    "yu=v yue=ve yuan=van yun=vn yong=iong wu=u wa=ua wo=uo wai=uai wei=ui "
    "wan=uan wen=un wang=uang weng=ueng").split())


def zhuyin(code):
    initial = next((item for item in (code[:2], code[:1]) if item in INITIALS), "")
    final = SEMIVOWELS.get(code, code[len(initial):])
    if initial in {"j", "q", "x"} and final.startswith("u"):
        final = "v" + final[1:]
    if initial in {"zh", "ch", "sh", "r", "z", "c", "s"} and final == "i":
        return INITIALS[initial]
    if final in FINALS:
        return INITIALS.get(initial, "") + FINALS[final]
    return ""


def words(packed):
    return [part for part in packed.split("|") if part]


def cstr(value):
    return json.dumps(value, ensure_ascii=False)


def read_tables():
    pinyin, phones, japanese = {}, {}, {}
    for line in (DATA / "mandarin.tsv").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        key, sc, tc = line.split("\t")
        pinyin[key] = (list(sc), list(tc))
        phonetic = zhuyin(key)
        if phonetic and tc:
            code = "".join(ZHUYIN_KEYS[ch] for ch in phonetic)
            phones[code] = list(dict.fromkeys(phones.get(code, []) + list(tc)))
    for line in (DATA / "phrases.tsv").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        mode, key, *entries = line.split("\t")
        if mode == "zh":
            prefix = tuple(words(entry) for entry in entries)
            pinyin[key] = tuple(list(dict.fromkeys(a + b)) for a, b in
                                zip(prefix, pinyin.get(key, ([], []))))
        else:
            japanese[key] = words(entries[0])
    return pinyin, phones, japanese


def atlas_bitmap(char, face):
    img = Image.new("L", (16, 20))
    ImageDraw.Draw(img).text((0, -3), char, font=face, fill=255)
    levels = [(value + 42) // 85 for value in img.tobytes()]
    return [sum(levels[i + pos] << (6 - 2 * pos) for pos in range(4))
            for i in range(0, len(levels), 4)]


def generate():
    pinyin, phones, japanese = read_tables()
    glyphs = set(range(0xac00, 0xd7a4))
    glyphs.update(range(0x3131, 0x3164))
    glyphs.update(range(0x3041, 0x3097))
    glyphs.update(range(0x30a1, 0x30fd))
    glyphs.update(ord(ch) for ch in ZHUYIN_KEYS)
    for values in pinyin.values():
        for group in values:
            glyphs.update(ord(ch) for word in group for ch in word)
    for group in japanese.values():
        glyphs.update(ord(ch) for word in group for ch in word)
    glyphs.add(0xfffd)
    OUT.parent.mkdir(exist_ok=True)
    out = OUT.with_suffix(".tmp")
    face_path = os.environ.get("MAYOS_FONT", "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
    faces = {script: ImageFont.truetype(face_path, 15, index=index)
             for script, index in (("ja", 0), ("ko", 1), ("sc", 2), ("tc", 3))}
    # Render each character in a face with the corresponding script design.
    japanese_han = {ord(ch) for group in japanese.values() for word in group for ch in word}
    traditional = {ord(ch) for _, group in pinyin.values() for word in group for ch in word}
    simplified = {ord(ch) for group, _ in pinyin.values() for word in group for ch in word}
    with out.open("w") as f:
        f.write("/* Generated by scripts/ime_assets.py. */\n")
        for name, table, columns in (("pinyin", pinyin, 2), ("zhuyin", phones, 1), ("japanese", japanese, 1)):
            f.write(f"static const MayImeEntry ime_{name}[] = {{\n")
            for key, group in sorted(table.items()):
                values = group if columns == 2 else (group, [])
                f.write("    {" + ", ".join(cstr(item) for item in (key, *("|".join(x) for x in values))) + "},\n")
            f.write("};\n")
        f.write("static const char ime_zhuyin_keys[] = " + cstr("".join(ZHUYIN_KEYS.values())) + ";\n")
        f.write("static const unsigned short ime_zhuyin_code[] = {" + ",".join(str(ord(ch)) for ch in ZHUYIN_KEYS) + "};\n")
        f.write("#ifdef MAY_IME_RENDER\n")
        f.write("static const unsigned short ime_glyph_codes[] = {" + ",".join(map(str, sorted(glyphs))) + "};\n")
        f.write("static const unsigned char ime_glyphs[][80] = {\n")
        for cp in sorted(glyphs):
            if 0xac00 <= cp <= 0xd7a3 or 0x3131 <= cp <= 0x3163:
                script = "ko"
            elif 0x3041 <= cp <= 0x30fa or cp in japanese_han - simplified - traditional:
                script = "ja"
            elif cp in traditional and cp not in simplified:
                script = "tc"
            else:
                script = "sc"
            f.write("{" + ",".join(map(str, atlas_bitmap(chr(cp), faces[script]))) + "},\n")
        f.write("};\n#endif\n")
    out.replace(OUT)
    print(f"IME: {len(pinyin)} Pinyin keys, {len(phones)} Zhuyin keys, {len(japanese)} Kanji lookups, {len(glyphs)} glyphs")


if __name__ == "__main__":
    generate()
