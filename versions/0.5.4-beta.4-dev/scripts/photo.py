#!/usr/bin/env python3
"""Pack local Easter egg artwork as aspect-preserving RGB565 bitmaps."""
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]


def image_definition(path, name, bounds):
    with Image.open(path) as original:
        image = ImageOps.exif_transpose(original).convert("RGB")
        image.thumbnail(bounds, Image.Resampling.LANCZOS)
        width, height = image.size
        raw = image.tobytes()
    colors = [f"0x{((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3):04x}"
              for r, g, b in zip(raw[::3], raw[1::3], raw[2::3])]
    rows = [",".join(colors[i:i + 24]) + "," for i in range(0, len(colors), 24)]
    prefix = name.upper()
    return "\n".join([
        f"#define {prefix}_W {width}", f"#define {prefix}_H {height}",
        f"static const unsigned short {name}_rgb565[{prefix}_W * {prefix}_H] = {{",
        *rows, "};", "",
    ])


def main():
    output = ROOT / "build/cat_image.h"
    output.parent.mkdir(exist_ok=True)
    data = "/* Generated by scripts/photo.py. */\n"
    data += image_definition(ROOT / "assets/easter-cat.jpg", "cat", (360, 480))
    data += image_definition(ROOT / "assets/easter-tenshi.png", "tenshi", (900, 500))
    if not output.exists() or output.read_text() != data:
        output.write_text(data)


if __name__ == "__main__":
    main()
