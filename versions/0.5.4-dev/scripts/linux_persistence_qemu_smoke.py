#!/usr/bin/env python3
"""Real BIOS QEMU two-boot persistence acceptance on disposable ext4 images.

Uses the *CI-only* GRUB opt-in entry generated by inject_qemu_persist_menu.py.
Never uses real host disks; does not claim physical USB/SATA/NVMe compatibility.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from dual_boot_smoke import BootVM, BUILD  # noqa: E402

MENU = "Linux 7.3.1 - QEMU PERSISTENCE TEST ONLY (/dev/sda)"
WRITING = "saved-across-real-qemu-reboots"


def sha(path: Path) -> str:
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def create_ext4(folder: Path, name: str, enabled: bool) -> Path:
    disk = folder / name
    with disk.open("xb") as target:
        target.truncate(128 * 1024 * 1024)
    seed = folder / (name + ".seed")
    seed.mkdir(mode=0o755)
    if enabled:
        marker = seed / ".mayos-profile-enabled"
        marker.write_text("MayOS-Profile-v1\n")
        marker.chmod(0o644)
        # Guest's UID=0 must own the marker; GitHub runners are nonroot.
        chown = ["chown", "0:0", str(seed), str(marker)]
        if os.geteuid() != 0:
            chown.insert(0, "sudo")
        subprocess.run(chown, check=True)
    try:
        # Copy original root-owned marker into an isolated ext4 disk image.
        subprocess.run(["mkfs.ext4", "-F", "-q", "-d", str(seed), str(disk)],
                       check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    finally:
        # Restore runner ownership so TemporaryDirectory can clean up; the
        # ext4 image has already recorded the guest root UID/GID.
        if enabled and os.geteuid() != 0:
            subprocess.run(["sudo", "chown", "-R",
                            f"{os.getuid()}:{os.getgid()}", str(seed)], check=True)
    return disk


def choose_test_linux(vm: BootVM):
    vm.wait(MENU, timeout=55)
    # Order in temporary GRUB: MayKernel, normal Linux, TEST Linux, rescue.
    vm.key("down")
    vm.key("down")
    vm.key("ret")


def boot(iso: Path, disk: Path, label: str) -> BootVM:
    vm = BootVM(iso=iso, disk=disk, tag=label,
                qemu="qemu-system-x86_64", memory=1024, timeout=150)
    try:
        choose_test_linux(vm)
        vm.wait("MayOS Linux: ready", timeout=145)
        vm.wait("MayOS: desktop ready", timeout=80)
        return vm
    except BaseException:
        vm.stop()
        raise


def qemu_host_screens(vm: BootVM, label: str, target: Path):
    src = vm.shot(label)
    if src.resolve() != target.resolve():
        shutil.copyfile(src, target)
    assert target.is_file() and target.stat().st_size > 15000


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--iso", required=True, type=Path)
    args = parser.parse_args()
    iso = args.iso.resolve()
    if not iso.is_file():
        parser.error(f"Test ISO missing: {iso}")
    BUILD.mkdir(parents=True, exist_ok=True)
    results = {}
    with tempfile.TemporaryDirectory(prefix="mayos-profile-qemu-") as temp:
        folder = Path(temp)
        marked_disk = create_ext4(folder, "marked-profile.img", True)
        empty = create_ext4(folder, "unmarked-profile.img", False)
        empty_hash = sha(empty)
        marked_hash = sha(marked_disk)

        vm = boot(iso, marked_disk, "linux-persist-first-boot")
        try:
            vm.wait("MayOS Linux profile: explicit marked ext4 mounted")
            vm.wait("MayOS Linux: empty marked profile")
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("write Documents/persist-test.txt " + WRITING)
            vm.wait("\nOK\n", offset=offset, timeout=30)
            qemu_host_screens(vm, "linux-persist-first", BUILD / "linux-persist-first.png")
            vm.shutdown()
        finally:
            vm.stop()
        assert sha(marked_disk) != marked_hash, "Marked profile disk was not written"
        results["first_boot_saved"] = "PASS"
        print("PASS: marked ext4 mounted; GUI saved a real desktop file", flush=True)

        vm = boot(iso, marked_disk, "linux-persist-second-boot")
        try:
            vm.wait("MayOS Linux: persistent desktop profile restored")
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("cat Documents/persist-test.txt")
            vm.wait("\n" + WRITING + "\n", offset=offset, timeout=30)
            qemu_host_screens(vm, "linux-persist-second", BUILD / "linux-persist-second.png")
            vm.shutdown()
        finally:
            vm.stop()
        results["second_boot_restored"] = "PASS"
        print("PASS: second real Linux64 boot restored the original GUI file", flush=True)

        # A successful GUI save includes file fsync + atomic rename +
        # directory fsync. The next shutdown deliberately kills the QEMU
        # process WITHOUT telling Linux to sync or unmount the ext4 volume.
        # This tests dirty-journal and abrupt-host-power-loss recovery, rather
        # than merely testing normal guest shutdown and clean ext4 mounts.
        after_cut = "survived-abrupt-qemu-power-loss"
        vm = boot(iso, marked_disk, "linux-persist-abrupt-cut")
        try:
            vm.wait("MayOS Linux: persistent desktop profile restored")
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("write Documents/persist-test.txt " + after_cut)
            vm.wait("\nOK\n", offset=offset, timeout=35)
            vm.pump()
            vm.proc.kill()  # intentionally unclean: no poweroff command/QMP quit
            vm.proc.wait(timeout=10)
        finally:
            vm.stop()
        results["abrupt_qemu_power_loss_after_fsync"] = "PASS"
        print("PASS: deliberately killed QEMU immediately after a committed desktop save", flush=True)

        vm = boot(iso, marked_disk, "linux-persist-after-powercut")
        try:
            vm.wait("MayOS Linux: persistent desktop profile restored", timeout=50)
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("cat Documents/persist-test.txt")
            vm.wait("\n" + after_cut + "\n", offset=offset, timeout=35)
            qemu_host_screens(vm, "linux-persist-after-powercut",
                              BUILD / "linux-persist-after-powercut.png")
            vm.shutdown()
        finally:
            vm.stop()
        results["power_loss_reboot_readback"] = "PASS"
        print("PASS: Linux64 cold-reboot after abrupt power cut restored fsync'ed GUI file", flush=True)

        vm = boot(iso, empty, "linux-persist-unmarked-boot")
        try:
            vm.wait("MayOS Linux profile: explicit marker missing; will not write")
            vm.wait("MayOS Linux: RAM filesystem; no persistent volume opened")
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("write Documents/ram-only.txt never-persistent")
            vm.wait("\nOK (RAM only; disk sync unavailable)\n", offset=offset, timeout=30)
            vm.shutdown()
        finally:
            vm.stop()
        assert sha(empty) == empty_hash, (
            "FAIL: no-marker test disk changed after guest boot; unsafe"
        )
        results["unmarked_ext4_disk_unchanged"] = "PASS"
        # The test covers a clean shutdown; also verify that a future
        # kernel journaling change cannot modify an unmarked disk.
        vm = boot(iso, empty, "linux-persist-unmarked-powercut")
        try:
            vm.wait("MayOS Linux profile: explicit marker missing; will not write")
            vm.key("f1")
            offset = len(vm.text)
            vm.keyboard_command("write Documents/ram-only.txt keep-disk-unchanged")
            vm.wait("\nOK (RAM only; disk sync unavailable)\n", offset=offset,
                    timeout=35)
            vm.proc.kill()
            vm.proc.wait(timeout=10)
        finally:
            vm.stop()
        assert sha(empty) == empty_hash, (
            "FAIL: unmarked ext4 disk changed after abrupt QEMU termination")
        results["unmarked_powercut_disk_unchanged"] = "PASS"
        print("PASS: unmarked ext4 disk remains byte-identical after QEMU power cut", flush=True)
        print("PASS: unmarked ext4 QEMU disk byte-identical despite GUI RAM edits", flush=True)

    results["iso_sha256"] = sha(iso)
    (BUILD / "linux-persistence-qemu-results.json").write_text(
        json.dumps(results, indent=2) + "\n")
    print("PASS: all real Linux64 persistence reboot and no-marker QEMU tests", flush=True)


if __name__ == "__main__":
    main()
