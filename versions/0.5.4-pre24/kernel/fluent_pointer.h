static inline void may_draw_system_pointer(u32 *surface, int x, int y, int height, int invert) {
    int width = (MAY_POINTER_W * height + MAY_POINTER_H - 1) / MAY_POINTER_H;
    for (int row = 0; row < height && y + row < H; row++) {
        if (y + row < 0) continue;
        for (int col = 0; col < width && x + col < W; col++) {
            if (x + col < 0) continue;
            u32 pixel = may_pointer_argb[(row * MAY_POINTER_H / height) * MAY_POINTER_W +
                                         col * MAY_POINTER_W / width];
            u32 alpha = pixel >> 24;
            if (!alpha) continue;
            u32 rgb = (pixel & 0xffffffu) ^ (invert ? 0xffffffu : 0);
            u32 *dst = surface + (y + row) * W + x + col;
            u32 color = 0;
            for (unsigned shift = 0; shift <= 16; shift += 8) {
                u32 foreground = (rgb >> shift) & 255, background = (*dst >> shift) & 255;
                color |= ((foreground * alpha + background * (255 - alpha) + 127) / 255) << shift;
            }
            *dst = color;
        }
    }
}

